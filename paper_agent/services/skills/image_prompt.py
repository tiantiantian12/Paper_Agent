"""图片提示词规范（自制 skill 的「提示词工程」部分，图片侧）。

和 :mod:`paper_agent.services.skills.video_prompt` 一个套路：规则放在**模型看得到的地方**
（``generate_image`` 的工具说明与参数说明），所以模型写提示词、决定要不要给参考图时会
自动照着来，不靠用户每次叮嘱。

**为什么单独立一块**（真实事故，不是假想）：

用户传了人物照片、要求「做定妆图」，模型只填了 ``prompt``、没填 ``reference_image`` ——
那就是纯文生图，出来的**是另一张脸**；用户看到「和照片里的人不像」，第一反应是「你没按
我的照片做」。第二次它填了参考图，但提示词写成了「电影级 3D 渲染 + 灰尘 + 疲惫感」，
风格词把五官盖掉了，用户还是判「不像本人」。

所以这块要钉住三件事，缺一件都会重演：

1. **传了人物照片、要「按这个形象 / 定妆图 / 保持五官」→ 必须填 ``reference_image``**
   （客户端还有兜底会自动挂，但不能指望兜底 —— 兜底只看提示词里的关键词）；
2. **图生图也是「重画」**：风格词越重越容易盖掉五官，提示词里要写明「严格保留五官、
   不改脸型」，风格词放轻；
3. **别把定妆图当中间产物**：用户最终要的是「视频里像本人」时，每多经过一次生成就少
   一分像（原照片 → 视频是 1 次生成；原照片 → 图生图 → 视频是 2 次）—— 直接把**原照片**
   交给 ``generate_video`` 的 ``anchor``。
"""

from __future__ import annotations

# ---------------------------------------------------------------- 给模型看的（中文）
# 硬规则：人物形象类必须带参考图
REFERENCE_RULE = (
    "**用户传了人物照片、要「按这个形象 / 做定妆图 / 保持五官」时，必须填 "
    "reference_image** —— 只给文字描述的话，出来的是**另一张脸**（模型按描述重画），"
    "用户会以为你没按他的照片做。照片在本会话文件清单里（先用 list_artifacts 看准确"
    "文件名）。"
)
# 一次可以给多张 + 参考图从哪来
MULTI_RULE = (
    "reference_image 可以是：本会话已有图片的**文件名**、本地图片路径，或图片 URL；"
    "**一次能给多张**（逗号分开，如「角色A.png,角色B.png」）—— 两个人各来一张定妆图、"
    "或人物和场景各给一张时就这么写。"
)
# 图生图仍是重画：风格词要轻
FIDELITY_RULE = (
    "图生图仍然是**重画**，不是抠图换背景：风格词越重越容易盖掉五官。要保住长相就"
    "在提示词里写明「**严格保留五官与脸型、不要改变面部特征**」，把「电影级 3D 渲染 / "
    "灰尘 / 疲惫感」这类改造词**放轻或去掉** —— 实测风格词堆多了，出来的会被判「不像本人」。"
)
# 别把定妆图当中间产物
NO_INTERMEDIATE_RULE = (
    "反过来，用户最终要的是**视频里像本人**时，别先出一张定妆图当中间产物 —— "
    "直接把**原照片**交给 generate_video 的 `anchor`（每多经过一次生成就少一分像："
    "原照片→视频是 1 次生成，原照片→图生图→视频是 2 次，少一次重画就多一分像）。"
)

# 拼起来放进工具说明
IMAGE_GUIDE = "\n".join((REFERENCE_RULE, MULTI_RULE, FIDELITY_RULE, NO_INTERMEDIATE_RULE))

# `reference_image` 参数自己的说明（写参数时模型也看这里）
REFERENCE_PARAM_HINT = (
    "参考图（图生图）：图片 URL、本地图片路径，或本会话里已有图片的文件名；"
    "多张用逗号分开（如「角色A.png,角色B.png」）。要把某张图改成别的风格 / 基于某张图"
    "继续创作、**或按某个人物的长相做定妆图**时填它 —— 人物形象类**必须**填，"
    "否则出来的是另一张脸"
)

# `prompt` 参数的写作要求：人物类要写清「保留五官」
PROMPT_PARAM_HINT = (
    "图片提示词，越具体越好（主体 / 风格 / 构图 / 光线）。"
    "**要长得像参考图里的人**时，明确写上「严格保留五官与脸型、不改变面部特征」，"
    "并少用会盖掉脸的强风格词"
)
