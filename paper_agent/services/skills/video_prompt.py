"""视频提示词规范（自制 skill 的「提示词工程」部分）。

这些规则放在**模型看得到的地方**（``generate_video`` 的工具说明与参数说明），
所以模型在写 prompt / shots 时会自动照着来，不需要用户额外叮嘱。

来源与取舍：参考了开源社区里针对字节「即梦 Seedance 2.0」的提示词 skill
（``songguoxs/seedance-prompt-skill``，2835 star），但**只吸收与平台无关的三条**：

1. **五段式**：主体 → 动作序列 → 环境/光影 → 镜头语言 → 风格关键词
2. **时间线**：按整片时间轴写清每个时间段演什么（``0-4秒：… 4-8秒：…``）——
   客户端会按实际分段切开并重算时间戳（见 :mod:`…skills.video_timeline`）
3. **显式衔接点**：每段收在一个明确的画面上，它就是下一段的起点
4. **台词照常写**（见 :data:`DIALOGUE_RULE`）：人物真的会开口说话、成片带声音

**没抄的**（都是即梦平台专有，我们的供应商 ``agnes-video-2.5-flash`` 不认）：
``@图片1`` 引用语法、「全能参考」入口、``将@视频1延长15秒``、2K、4–15 秒上限 ——
发过去只会被当成普通文本。分段拼接它教的是**手工**延长，而我们已经有自动分段
（4–12 秒/段）+ 末帧/参考图衔接 + ffmpeg 无损合成，不需要照它做。

**注意「原生音效」这一条别照抄**：它把那归为平台专有，而我们的供应商**成片自带音轨**
（实测：每条 mp4 都带 AAC 立体声，人物会照常开口说台词）。所以**不要**学它那套
「先出画面 + 画外音 + 字幕」的保守工作流 —— 那会让成片变成没人说话的默片，用户还得
回头纠正（见 :data:`DIALOGUE_RULE`）。

**还要记住它的一条硬限制**：Seedance 不支持上传含**写实真人脸部**的素材（平台会拦）。
我们整条「像本人」的链路恰好是拿用户的真人照片当 anchor —— 若哪天换成那个平台，
这条路直接不可用，得提前跟用户说清。
"""

from __future__ import annotations

import re

# ---------------------------------------------------------------- 给模型看的（中文）
# 写进工具说明：模型据此写 prompt 与分镜
FIVE_PART_RULE = (
    "**提示词按五段式写**：① 主体（谁 / 什么，带可辨识特征）→ ② 动作序列（按时间先后，"
    "一步一句）→ ③ 环境与光影 → ④ 镜头语言（景别 + 运镜）→ ⑤ 风格关键词（胶片颗粒、"
    "冷灰蓝调、电影感…）。用自然语言整句写，别堆一串关键词。"
)
# 时间线规则（最重要的一条）：
# 用户的原话是「我要模型按时间线划分好每个时间点的画面内容后，视频模型按划分好的来」。
# 实测（2026-09-23，一条 12 秒提示词里写 0-4/4-8/8-12 秒）：视频模型**会**按时间线演，
# 包括在时间段之间切换景别 / 机位。所以关键不是「能不能切」，而是「时间线写全了没有」：
# 每条都从自己的 0 重新计时会很乱，客户端按时间线切片时也认不出来（见 video_timeline）。
TIMELINE_RULE = (
    "**先把整条片子的时间戳写清**（最重要）：从 0 开始、**连续铺满你请求的总时长**，"
    "每个时间段写清「这几秒演什么画面」，例如 12 秒："
    "`0-4秒：… 4-8秒：… 8-12秒：…`；30 秒就写到 30 秒（`0-10秒 / 10-20秒 / 20-30秒`）。"
    "**客户端会按实际分段（每段 ≤12 秒）自动把这条时间线切开**，把每个时间段落到对应的那一段，"
    "并把时间戳重算成「这一段自己的 0 起点」—— 所以你**按整片时间轴写就行，不用猜我们分几段**。"
    "实测视频模型会照着时间线演（包括切换景别 / 机位），所以："
    "① 每个时间段都要写清画面内容，**别留空**（没铺满总时长时，客户端只能给最后那一段补一句"
    "「把剩下的时间往下演」，那几秒就由模型自己发挥）；"
    "② 一个时间段建议 3–6 秒（太短切不出来、太长容易没变化），**切换画面就换一个时间段**"
    "（同一个时间段里别切景别 / 机位）；"
    "③ 时间段之间写清换什么（景别 / 机位 / 人物动作），别把一个画面复制到每一段；"
    "④ **全片共用的描述写在第一个时间点之前**（风格、色调、颗粒、场景基调、人物固定措辞）——"
    "客户端会把这段前言带进每一段；写在**最后一个时间点之后**的只会进最后那一段，"
    "前面的段就丢了这些风格词。"
)
HANDOFF_RULE = (
    "**每个时间段都要收在一个明确的画面上**：把最后一个镜头收在看得清主体、光线正常的地方，"
    "别停在动作中间或糊镜头里 —— 那个画面就是下一段的起点（首尾帧模式直接拿它当首帧），"
    "也是整条片子接得上、不跳帧的关键。"
)
# 台词 / 说话：**别让模型自己把台词「救」成画外音或字幕。**
#
# 实测（2026-09-24）：供应商回来的成片**自带音轨**（`data/artifacts/` 里每条 mp4 都是
# h264 + AAC 立体声），人物会真的开口说台词，口型也对得上。但小模型普遍带一个先验 ——
# 「视频模型做不了口型，得后期配音 + 字幕」，于是它会主动把用户写的「林越说：『信号没了。』」
# 改写成画外音 / 旁白，甚至干脆不写台词，成片就变成没人说话的默片；用户还得回头纠正它
# （真实会话里它就是这么劝用户的）。所以这条必须写进**模型看得到**的规范里。
DIALOGUE_RULE = (
    "**人物是可以说话的，台词照常写就行**（不要自己改成画外音 / 字幕 / 后期配音）："
    "直接写「某某说：『台词』」，视频模型会让人物开口说话 —— 口型对得上，成片也带声音。"
    "写法三点：① **一句话配一个时间点**（`4-8秒：… 他抬头说：『信号没了。』`），"
    "别把整段对白塞进同一个时间点；② **说话时把镜头给说话的人**（近景 / 中近景，嘴在画面里）；"
    "③ 台词写短：按**每秒 3–5 个字**估，一句话七八个字以内最稳，太长会被压成快放。"
    "内心独白 / 旁白也照写，但要明确标出「画外音：…」（不标的话模型会让人张嘴念出来）。"
)
PROMPT_GUIDE = "\n".join((FIVE_PART_RULE, TIMELINE_RULE, DIALOGUE_RULE, HANDOFF_RULE))

# `shots` 参数的写法要求：**每条是一个时间段的画面**（整片时间轴上的一段）
SHOTS_GUIDE = (
    "**每条是一个字符串**（不要写成一个对象 / 字典），每条对应**整片时间轴上的一段**，"
    "带上它的秒数范围（`12-24秒：…`），合起来从 0 连续铺满总时长（如 30 秒 → 3 条："
    "`0-10秒：开场…` / `10-20秒：中段…` / `20-30秒：收尾…`）—— "
    "**不要每条都从 0 重新计时**，那是「每段自己的时间轴」，客户端会认不出整片时间线。"
    "每条按五段式写；**每条结尾写清这一段收在什么画面上**（下一条从那儿接）。"
    "**每条必须是不同的情节推进**（接着上一段往下演），不要重复前面演过的动作与台词，"
    "也别把同一幕换个说法写两三遍 —— 注意「接着演」不等于「把上一条的动作再演一遍」："
    "上一条已经起床了，下一条就写「起身之后」的事，别又从起床开始"
    "（客户端会把「前面已经演过什么」摘要给每一段，重复的段落会被当成重播）"
)

# ---------------------------------------------------------------- 给视频模型看的（中文）
# 追加到每一段的末尾。**与用户 / 模型写的提示词同一种语言**：工具说明、分镜规范、这些锚点
# 是同一条链路上的东西，整条链路统一中文，模型读到的是一段连贯的中文指令，用户也能一眼看懂
# 我们在要求什么。
# （若哪天实测某个模型对英文运镜术语更敏感，该做的是**只把运镜词**写成中英并列，
#   而不是把整段约束换成英文 —— 一屏两种语言反而稀释指令。）
HANDOFF_LINE = (
    "\n\n这一段请收在一个清晰、稳定的画面上，好让下一段从这里接下去：{next}\n"
    "不要在动作中途切断，也不要收在模糊或被遮挡的画面上。"
)
# 没给分镜（几段共用一句话）时的通用衔接说法：没有"下一段画面"可以点名
HANDOFF_LINE_GENERIC = (
    "\n\n这一段请收在一个清晰、稳定的画面上，好让下一段从这里接下去"
    "（主体与场景保持一致；不要在动作中途切断，也不要收在模糊或被遮挡的画面上）。"
)
CLOSING_LINE = (
    "\n\n这是整条片子的最后一个镜头：收在一个明确的收尾画面上"
    "（干净的远景、停住的表情，或片名卡），并让镜头稳住。"
)
SHOT_SNIPPET_CHARS = 120        # 下一段分镜只取一小段，别把预算吃光

# 时间线没铺满这一段时补的话。
#
# 实测（2026-09-23 的丧尸短片，10 秒/段）：时间线只写到「0-7秒：沉睡→惊醒→坐起」，
# 而这一段实际有 10 秒 —— 末尾 3 秒没有指令，视频模型就自己补，最常见的补法就是
# **原地重演刚才的画面**，用户看到的就是「第 1 段和第 2 段内容重复」。所以这里补一句
# 明确要求：剩下的时间要往前演。
#
# 只在这段**确实用了时间戳**、且没铺满时才补（没写时间戳的短镜头不打扰）。
# **单段（≤12 秒）也走这里** —— 一段片子同样会「没铺满」（写 0-7 秒却要 8 秒）。
PAD_LINE = (
    "\n\n这一段要占满全部 {seconds} 秒：上面这些时间点演完之后，"
    "继续把故事往下推（新的动作 / 新的镜头运动），不要重演、拖长或停在原地。"
)
RE_TIMESTAMP = re.compile(r"(\d+(?:\.\d+)?)\s*秒")
PAD_MIN_GAP = 2.0               # 时间戳与段长差不到 2 秒就不啰嗦了


def _snippet(text: str, limit: int = SHOT_SNIPPET_CHARS) -> str:
    """把一段分镜压成一句短的（写进衔接点里用）。"""
    flat = " ".join(str(text or "").split())
    return flat if len(flat) <= limit else flat[:limit] + "…"


def handoff_block(next_shot: str = "") -> str:
    """这一段的「衔接点」：结尾要收在下一段能接住的画面上。

    下一段的提示词我们手里就有（模型给的分镜），所以能写出**具体**的衔接目标，
    而不是空泛地说一句「注意衔接」；没给分镜（几段共用一句话）时退化成通用说法。
    """
    target = _snippet(next_shot)
    if not target:
        return HANDOFF_LINE_GENERIC
    return HANDOFF_LINE.format(next=target)


def closing_block() -> str:
    """最后一段的收尾提示（没有下一段可接了，就收干净）。"""
    return CLOSING_LINE


def pad_block(shot_text: str, seconds: float) -> str:
    """分镜的时间戳没铺满这一段时补的话（没写时间戳就不补）。

    Args:
        shot_text: 这条分镜的正文（**不含**我们后面追加的锚点 —— 锚点里的
            「已演过什么」摘要会引用前几段的秒数，那会把判断带偏）。
        seconds: 这一段的实际时长。
    """
    if seconds <= 0:
        return ""
    stamps = [float(item) for item in RE_TIMESTAMP.findall(shot_text or "")]
    if not stamps:
        return ""                      # 没用时间戳：不打扰
    if max(stamps) > seconds - PAD_MIN_GAP:
        return ""                      # 时间戳已经铺满（或超了）：本来就不会原地打转
    return PAD_LINE.format(seconds=int(seconds))
