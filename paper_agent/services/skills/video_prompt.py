"""视频提示词规范（自制 skill 的「提示词工程」部分）。

这些规则放在**模型看得到的地方**（``generate_video`` 的工具说明与参数说明），
所以模型在写 prompt / shots 时会自动照着来，不需要用户额外叮嘱。

来源与取舍：参考了开源社区里针对字节「即梦 Seedance 2.0」的提示词 skill
（``songguoxs/seedance-prompt-skill``，2835 star），但**只吸收与平台无关的三条**：

1. **五段式**：主体 → 动作序列 → 环境/光影 → 镜头语言 → 风格关键词
2. **时间线**：按整片时间轴写清每个时间段演什么（``0-4秒：… 4-8秒：…``）——
   客户端会按实际分段切开并重算时间戳（见 :mod:`…skills.video_timeline`）
3. **显式衔接点**：每段收在一个明确的画面上，它就是下一段的起点
4. **台词照常写**（见 :data:`DIALOGUE_RULE`）：人物真的会开口说话、成片带声音

**没抄的**（都是即梦平台专有，我们的供应商 ``agnes-video-2.5-flash`` 不认）：
``@图片1`` 引用语法、「全能参考」入口、``将@视频1延长15秒``、2K、4–15 秒上限 ——
发过去只会被当成普通文本。分段拼接它教的是**手工**延长，而我们已经有自动分段
（5–12 秒/段）+ 末帧/参考图衔接 + ffmpeg 无损合成，不需要照它做。

**注意「原生音效」这一条别照抄**：它把那归为平台专有，而我们的供应商**成片自带音轨**
（实测：每条 mp4 都带 AAC 立体声，人物会照常开口说台词）。所以**不要**学它那套
「先出画面 + 画外音 + 字幕」的保守工作流 —— 那会让成片变成没人说话的默片，用户还得
回头纠正（见 :data:`DIALOGUE_RULE`）。

**还要记住它的一条硬限制**：Seedance 不支持上传含**写实真人脸部**的素材（平台会拦）。
我们整条「像本人」的链路恰好是拿用户的真人照片当 anchor —— 若哪天换成那个平台，
这条路直接不可用，得提前跟用户说清。
"""

